const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('board receipt supports pending dimensions and money without fabricated supplier debt', () => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'warehouse-board-optional-'));
  process.env.WAREHOUSE_DATA_FILE = path.join(temporary, 'data.json');
  process.env.WAREHOUSE_BACKUP_DIR = path.join(temporary, 'backups');
  process.env.WAREHOUSE_DIMENSIONS_FILE = path.join(temporary, 'dimensions.json');
  fs.writeFileSync(process.env.WAREHOUSE_DATA_FILE, JSON.stringify({ products: [], customers: [], suppliers: [], transactions: [], ledger: [] }));
  const db = require('./db');
  const supplier = db.addSupplier({ name: '待补板厂' });
  const raw = { supplier_id: supplier.id, supplier: supplier.name, date: new Date().toLocaleDateString('en-CA'), boardDimensionsPending: true, boardLength: 0, boardWidth: 0, cartonLength: 30, cartonWidth: 20, cartonHeight: 15, fluteType: 'B', layers: 3, orderedQty: 20, receivedQty: 20, billedArea: 0, unitPrice: 0, amountMode: 'pending' };
  const pending = db.receiveBoard(raw);
  assert.equal(pending.amountMode, 'pending');
  assert.equal(db.getSupplier(supplier.id).payable, 0);
  assert.equal(pending.ledger_id, undefined);
  db.validateBackup(db.backupData());
  const manual = db.updateBoard(pending.id, { ...raw, amountMode: 'manual', manualAmount: 78.4 });
  assert.equal(manual.amount, 78.4);
  assert.equal(manual.createdAt, pending.createdAt);
  assert.equal(db.getSupplier(supplier.id).payable, 78.4);
  db.validateBackup(db.backupData());
  const completed = db.updateBoard(pending.id, { ...raw, boardDimensionsPending: false, boardLength: 120, boardWidth: 80, billedArea: 19.2, unitPrice: 2, amountMode: 'area' });
  assert.equal(completed.boardDimensionsPending, undefined);
  assert.equal(completed.amountMode, undefined);
  assert.equal(completed.amount, 38.4);
  assert.equal(db.getSupplier(supplier.id).payable, 38.4);
  db.validateBackup(db.backupData());
  const usedPending = db.receiveBoard(raw);
  db.moveBoard(usedPending.id, { type: 'out', quantity: 5, remark: '生产领料' });
  assert.throws(() => db.updateBoard(usedPending.id, { ...raw, receivedQty: 25, amountMode: 'manual', manualAmount: 40 }), /只能补录待补金额/);
  const lateAmount = db.updateBoard(usedPending.id, { ...raw, amountMode: 'manual', manualAmount: 40 });
  assert.equal(lateAmount.remainingQty, 15);
  assert.equal(lateAmount.movements.length, 2);
  assert.equal(db.getSupplier(supplier.id).payable, 78.4);
  db.validateBackup(db.backupData());
  assert.throws(() => db.receiveBoard({ ...raw, boardLength: 12 }), /待补纸板尺寸/);
  assert.throws(() => db.receiveBoard({ ...raw, amountMode: 'pending', billedArea: 3, unitPrice: 2 }), /计算货款/);
});
