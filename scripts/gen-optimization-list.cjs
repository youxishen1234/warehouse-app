// ---------------- 生成矩阵条目（轮询交织，保证覆盖面） ----------------
function buildMatrix() {
  const lists = [];
  // 仅保留无登录环境下实际存在的接口（移除 team/audit 与 login/gate/me/logout/password）
  const activeEndpoints = ENDPOINTS.filter(e =>
    !/^\/api\/(team|audit)/.test(e[1]) &&
    !/^\/api\/auth\/(login|gate|me|logout|password)/.test(e[1]));
  // A. 页面 × 关注点
  lists.push(PAGES.flatMap(([key, name]) => PAGE_CONCERNS.map(fn => fn(name, key))));
  // B. 字段 × 校验
  lists.push(FIELDS.flatMap(([page, key, name, kind]) => FIELD_CHECKS.map(fn => fn(name, kind, kind, page, key))));
  // C. 接口 × 检查
  lists.push(activeEndpoints.flatMap(e => ENDPOINT_CHECKS.map(fn => fn(e[0], e[1], e[2], e[3]))));
  // D. 接口 × 负面
  lists.push(activeEndpoints.flatMap(e => ENDPOINT_NEGATIVE.map(fn => fn(e[0], e[1], e[2], e[3]))));
  // E. 页面 × E2E
  lists.push(PAGES.flatMap(([key, name]) => PAGE_E2E.map(fn => fn(name, key))));

  // 轮询交织
  const maxLen = Math.max(...lists.map(l => l.length));
  const merged = [];
  for (let i = 0; i < maxLen; i++) for (const l of lists) if (l[i] !== undefined) merged.push(l[i]);
  return merged;
}

