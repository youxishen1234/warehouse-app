const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const filename=path.resolve('src/pages/print-center/specification-input.ts');
const loaded=new Module(filename,module);loaded.filename=filename;loaded.paths=module.paths;
loaded._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {formatSpecificationInput:format}=loaded.exports;
test('three-digit dimensions insert separators during numeric typing and accept pasted dimensions',()=>{
 let value=''; for(const digit of '400300200')value=format(value+digit,value);
 assert.equal(value,'400×300×200');
 assert.equal(format('40'),'40');assert.equal(format('400'),'400×');
 assert.equal(format('400300'),'400×300×');
 assert.equal(format('400300200'),'400×300×200');
 assert.equal(format('40x30*20'),'40×30×20');
 assert.equal(format('400×300×200'),'400×300×200');
 assert.equal(format('400×300×20','400×300×200'),'400×300×20');
 assert.equal(format('400','400×'),'400');
 assert.equal(format('40','400'),'40');
 assert.equal(format(''),'');
});
test('two-digit mode inserts separators, preserves completed dimensions and allows deletion',()=>{
 let value='';for(const digit of '403020')value=format(value+digit,value,2);
 assert.equal(value,'40×30×20');
 assert.equal(format('40','',2),'40×');
 assert.equal(format('4030','',2),'40×30×');
 assert.equal(format('403020','',2),'40×30×20');
 assert.equal(format('40','40×',2),'40');
 assert.equal(format('40×30×2','40×30×20',2),'40×30×2');
 assert.equal(format('400×300×200','',2),'400×300×200');
 assert.equal(format('40x30*20','',2),'40×30×20');
 assert.equal(format('40×300','40×30',3),'40×300×');
});
