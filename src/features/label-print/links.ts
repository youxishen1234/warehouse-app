export const LABEL_ORIGIN = 'https://youxishen.online';
export const LABEL_RESOLVER_PATH = '/pages/management/index?section=label-lookup';
export const LABEL_LINK_VERSION = 1 as const;
export type LabelKind = 'finished-product' | 'paperboard-batch';
export type LabelTarget = Readonly<{ version: 1; kind: LabelKind; id: string }>;

export class LabelLinkError extends Error {
  constructor(message: string) { super(message); this.name = 'LabelLinkError'; }
}

export function validateLabelId(kind: LabelKind, id: unknown): string {
  const text = typeof id === 'number' && Number.isSafeInteger(id) ? String(id) : id;
  if (typeof text !== 'string') throw new LabelLinkError('标签记录编号无效');
  if (kind === 'finished-product' && /^[1-9][0-9]{0,15}$/.test(text) && Number.isSafeInteger(Number(text))) return text;
  // This is the stable ID format generated by the paperboard business API.
  if (kind === 'paperboard-batch' && /^BOARD-[0-9]{8}-[A-F0-9]{12}$/.test(text)) return text;
  throw new LabelLinkError('标签记录编号无效，请重新扫描完整标签');
}

function validateKind(kind: unknown): LabelKind {
  if (kind !== 'finished-product' && kind !== 'paperboard-batch') throw new LabelLinkError('不支持的标签类型');
  return kind;
}

export function parseLabelRouteParams(params: Record<string, unknown>): LabelTarget {
  if (!params || typeof params !== 'object' || Array.isArray(params)) throw new LabelLinkError('标签参数无效');
  const keys = Object.keys(params);
  const labelKeys = keys.filter(key => key !== 'section');
  if ((params.section !== undefined && params.section !== 'label-lookup') || labelKeys.length !== 3 || labelKeys.some(key => !['v', 'kind', 'id'].includes(key))) throw new LabelLinkError('标签参数缺失或包含未知字段');
  if (params.v !== '1') throw new LabelLinkError('不支持的标签版本，请联系仓库人员');
  if (typeof params.id !== 'string') throw new LabelLinkError('标签记录编号无效');
  const kind = validateKind(params.kind);
  return Object.freeze({ version: LABEL_LINK_VERSION, kind, id: validateLabelId(kind, params.id) });
}

export function parseLabelUrl(raw: string): LabelTarget {
  if (typeof raw !== 'string' || raw !== raw.trim() || raw.length > 512 || Array.from(raw).some(character => character.charCodeAt(0) <= 32 || character.charCodeAt(0) === 127) || !raw.startsWith(`${LABEL_ORIGIN}/#${LABEL_RESOLVER_PATH}&`)) {
    throw new LabelLinkError('这不是受支持的仓库标签链接');
  }
  let url: URL;
  try { url = new URL(raw); } catch (error) { throw new LabelLinkError('标签链接无效'); }
  if (url.origin !== LABEL_ORIGIN || url.protocol !== 'https:' || url.username || url.password || url.port || url.pathname !== '/' || url.search) {
    throw new LabelLinkError('标签站点或路径无效');
  }
  const [path, query, ...extra] = url.hash.slice(1).split('?');
  if (path !== '/pages/management/index' || !query?.startsWith('section=label-lookup&') || extra.length || query.includes('#')) throw new LabelLinkError('标签路径或参数无效');
  const entries = query.slice('section=label-lookup&'.length).split('&');
  if (entries.length !== 3) throw new LabelLinkError('标签参数缺失或重复');
  const params: Record<string, string> = {};
  for (const entry of entries) {
    const match = /^(v|kind|id)=([^=]*)$/.exec(entry);
    if (!match || Object.prototype.hasOwnProperty.call(params, match[1])) throw new LabelLinkError('标签包含重复或未知参数');
    try { params[match[1]] = decodeURIComponent(match[2]); } catch (error) { throw new LabelLinkError('标签参数编码无效'); }
  }
  return parseLabelRouteParams(params);
}

export function buildLabelUrl(kind: LabelKind, id: number | string): string {
  const checkedKind = validateKind(kind);
  const checkedId = validateLabelId(checkedKind, id);
  return `${LABEL_ORIGIN}/#${LABEL_RESOLVER_PATH}&v=${LABEL_LINK_VERSION}&kind=${checkedKind}&id=${encodeURIComponent(checkedId)}`;
}

/** Parse a page's raw URL before router parameter flattening can hide duplicate keys. */
export function parseLabelPageTarget(href: string | undefined, params: Record<string, unknown>): LabelTarget {
  if (href === undefined) return parseLabelRouteParams(params);
  let url: URL;
  try { url = new URL(href); } catch (error) { throw new LabelLinkError('标签页面地址无效'); }
  if (url.origin === LABEL_ORIGIN) return parseLabelUrl(href);
  const localHost = url.hostname === 'localhost' || url.hostname === '127.0.0.1' || url.hostname === '[::1]';
  const localProtocol = url.protocol === 'http:' || url.protocol === 'https:' || url.protocol === 'capacitor:';
  if (!localHost || !localProtocol || url.username || url.password || url.search || url.pathname !== '/') throw new LabelLinkError('标签站点或路径无效');
  // Local App and dev shells cannot be printed into QR payloads: buildLabelUrl always uses LABEL_ORIGIN.
  return parseLabelUrl(`${LABEL_ORIGIN}/${url.hash}`);
}
